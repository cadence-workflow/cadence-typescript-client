export async function sessionCreationActivity(ctx: Context, sessionID: string): Promise<void> {
  const value = ctx.value<sessionEnvironment>(sessionEnvironmentContextKey);
  if (value == null || typeof value !== "object" || typeof value.CreateSession !== "function") {
    throw "no session environment in context";
  }
  const sessionEnv = value as sessionEnvironment;

  const doneCh = await sessionEnv.CreateSession(ctx, sessionID);

  try {
    await sessionEnv.SignalCreationResponse(ctx, sessionID);

    const activityEnv = getActivityEnv(ctx);
    let heartbeatInterval = activityEnv.heartbeatTimeout / 3;
    if (heartbeatInterval > maxSessionHeartbeatInterval) {
      heartbeatInterval = maxSessionHeartbeatInterval;
    }

    const heartbeatRetryPolicy = NewExponentialRetryPolicy(Second);
    heartbeatRetryPolicy.SetMaximumInterval(Second * 2);
    heartbeatRetryPolicy.SetExpirationInterval(heartbeatInterval);

    for (;;) {
      const outcome = await selectOne([
        mapCase(recvCase(ctx.done()), () => ({ kind: "cancel" as const })),
        mapCase(timeoutCase(heartbeatInterval), () => ({ kind: "heartbeat" as const })),
        mapCase(recvCase(doneCh), () => ({ kind: "done" as const })),
      ]);

      if (outcome.kind === "cancel") {
        try {
          await sessionEnv.CompleteSession(sessionID);
        } catch (err) {
          if (!(err instanceof Error)) {
            throw err;
          }
        }
        const err = ctx.err();
        if (err != null) {
          throw err;
        }
        return;
      }

      if (outcome.kind === "done") {
        return;
      }

      const heartbeatOp = async (): Promise<void> => {
        await activityEnv.serviceInvoker!.Heartbeat(Buffer.alloc(0));
      };
      const isRetryable = (_err: Error | null): boolean => ctx.err() == null;

      try {
        await Retry(ctx, heartbeatOp, heartbeatRetryPolicy, isRetryable);
      } catch (err) {
        if (!(err instanceof Error)) {
          throw err;
        }
        GetActivityLogger(ctx).info("session heartbeat failed", {
          error: err,
          sessionID,
        });
      }
    }
  } finally {
    sessionEnv.AddSessionToken();
  }
}

export async function createSession(ctx: internal_Context, creationTasklist: string, options: internal_SessionOptions, retryable: boolean): Promise<internal_Context> {
  const logger = GetLogger(ctx);
  logger.debug("Start creating session");

  const prevSessionInfo = getSessionInfo(ctx);
  if (prevSessionInfo != null && prevSessionInfo.sessionState === sessionStateOpen) {
    throw errFoundExistingOpenSession;
  }

  const sessionID = await generateSessionID(ctx);
  const tasklistChan = GetSignalChannel(ctx, sessionID);

  const retryPolicy: internal_RetryPolicy = {
    InitialInterval: Second,
    BackoffCoefficient: 1.1,
    MaximumInterval: Second * 10,
    ExpirationInterval: options.CreationTimeout,
    MaximumAttempts: 0,
    NonRetriableErrorReasons: [
      "cadenceInternal:Panic",
      "cadenceInternal:Generic",
      "cadenceInternal:Timeout START_TO_CLOSE",
      "cadenceInternal:Timeout HEARTBEAT",
    ],
  };

  let heartbeatTimeout = defaultSessionHeartbeatTimeout;
  if (options.HeartbeatTimeout !== 0) {
    heartbeatTimeout = options.HeartbeatTimeout;
  }

  const ao: internal_ActivityOptions = {
    ActivityID: "",
    TaskList: creationTasklist,
    ScheduleToStartTimeout: options.CreationTimeout,
    ScheduleToCloseTimeout: 0,
    StartToCloseTimeout: options.ExecutionTimeout,
    HeartbeatTimeout: heartbeatTimeout,
    WaitForCancellation: false,
  };

  if (retryable) {
    ao.RetryPolicy = retryPolicy;
  }

  const sessionInfo = new internal_SessionInfo({
    SessionID: sessionID,
    sessionState: sessionStateOpen,
    HostName: "",
    resourceID: "",
    tasklist: "",
  });

  const completionCtx = setSessionInfo(ctx, sessionInfo);
  sessionInfo.completionCtx = completionCtx;

  const [sessionCtx, sessionCancelFunc] = await WithCancel(completionCtx);
  const creationCtx = WithActivityOptions(sessionCtx, ao);
  const creationFuture = await ExecuteActivity(creationCtx, sessionCreationActivityName, sessionID);

  let creationErr: Error | null = null;
  const creationResponseBox: { value: sessionCreationResponse } = {
    value: {
      Tasklist: "",
      HostName: "",
      ResourceID: "",
    },
  };

  const s = NewSelector(creationCtx);
  s.AddReceive(tasklistChan, async (c: internal_Channel, more: boolean) => {
    await c.Receive(creationCtx, creationResponseBox);
  });
  s.AddFuture(creationFuture, async (f: internal_Future) => {
    try {
      await f.Get(creationCtx, null);
    } catch (e) {
      if (!(e instanceof Error)) {
        throw e;
      }
      creationErr = e;
    }
    GetLogger(creationCtx).debug("Failed to create session", {
      sessionID,
      error: creationErr,
    });
  });
  await s.Select(creationCtx);

  if (creationErr != null) {
    await sessionCancelFunc();
    throw creationErr;
  }

  const creationResponse = creationResponseBox.value;
  sessionInfo.tasklist = creationResponse.Tasklist;
  sessionInfo.resourceID = creationResponse.ResourceID;
  sessionInfo.HostName = creationResponse.HostName;
  sessionInfo.sessionCancelFunc = sessionCancelFunc;

  Go(creationCtx, async (creationCtx: internal_Context) => {
    try {
      await creationFuture.Get(creationCtx, null);
      return;
    } catch (e) {
      if (!(e instanceof Error)) {
        throw e;
      }

      if (!(e instanceof internal_CanceledError)) {
        getWorkflowEnvironment(creationCtx).RemoveSession(sessionID);
        GetLogger(creationCtx).debug("Session failed", {
          sessionID,
          error: e,
        });
        sessionInfo.sessionState = sessionStateFailed;
        await sessionCancelFunc();
      }
    }
  });

  logger.debug("Created session", { sessionID });
  getWorkflowEnvironment(ctx).AddSession(sessionInfo);
  return sessionCtx;
}

