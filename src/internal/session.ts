/**
 * CompleteSession completes a session. It releases worker resources, so other sessions can be created.
 * CompleteSession won't do anything if the context passed in doesn't contain any session information or the
 * session has already completed or failed.
 * 
 * After a session has completed, user can continue to use the context, but the activities will be scheduled
 * on the normal taskList (as user specified in ActivityOptions) and may be picked up by another worker since
 * it's not in a session.
 */
export async function CompleteSession(ctx: internal_Context): Promise<void> {
    const sessionInfo = getSessionInfo(ctx);
    if (sessionInfo == null || sessionInfo.sessionState !== sessionStateOpen) {
        return;
    }

    await sessionInfo.sessionCancelFunc!();

    const completionCtx = WithActivityOptions(sessionInfo.completionCtx!, {
        ActivityID: "",
        HeartbeatTimeout: 0,
        ScheduleToCloseTimeout: 0,
        ScheduleToStartTimeout: 3 * Second,
        StartToCloseTimeout: 3 * Second,
        TaskList: "",
        WaitForCancellation: false,
    });

    try {
        const future = await ExecuteActivity(
            completionCtx,
            sessionCompletionActivityName,
            sessionInfo.SessionID,
        );
        await future.Get(completionCtx, undefined);
    } catch (err) {
        if (!(err instanceof Error)) {
            throw err;
        }
        GetLogger(completionCtx).warn("Complete session activity failed", { error: err });
    }

    sessionInfo.sessionState = sessionStateClosed;
    getWorkflowEnvironment(ctx).RemoveSession(sessionInfo.SessionID);
    GetLogger(ctx).debug("Completed session", { sessionID: sessionInfo.SessionID });
}

