export function decodeArgsToValues(dc: internal_DataConverter | undefined, fnType: unknown, data: Buffer): unknown[] {
	if (dc == null) {
		dc = getDefaultDataConverter();
	}

	const result: unknown[] = [];
	for (let i = 0; i < (fnType as Function).length; i++) {
		if (i === 0 && (isActivityContext(fnType) || isWorkflowContext(fnType))) {
			continue;
		}
		const arg: { value: unknown } = { value: undefined };
		result.push(arg);
	}

	dc!.FromData(data, ...result);
	return result;
}

