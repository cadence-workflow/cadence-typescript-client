export async function initBinaryChecksum(): Promise<string> {
  await binaryChecksumLock.acquire();
  try {
    if (typeof binaryChecksum === "string") {
      return binaryChecksum;
    }

    const executable = process.execPath;
    const checksum = createHash("md5")
      .update(readFileSync(executable))
      .digest("hex");

    binaryChecksum = checksum;
    return checksum;
  } finally {
    binaryChecksumLock.release();
  }
}

export async function getBinaryChecksum(): Promise<string> {
  if (typeof binaryChecksum === "string") {
    return binaryChecksum;
  }

  const bcsVal = await initBinaryChecksum();
  return bcsVal;
}

/**
 * tagScope with one or multiple tags, like
 * tagScope(scope, tag1, val1, tag2, val2)
 */
export function tagScope(metricsScope: Scope | undefined, ...keyValueinPairs: string[]): Scope {
  if (metricsScope == null) {
    metricsScope = NoopScope;
  }
  if (keyValueinPairs.length % 2 !== 0) {
    throw "tagScope key value are not in pairs";
  }
  const tagsMap: Record<string, string> = {};
  for (let i = 0; i < keyValueinPairs.length; i += 2) {
    tagsMap[keyValueinPairs[i]] = keyValueinPairs[i + 1];
  }
  return metricsScope.Tagged(tagsMap);
}

