export function decodeAndAssignValue(dc: internal_DataConverter, from: unknown, toValuePtr: unknown | undefined): void {
    if (toValuePtr == null) {
        return;
    }

    if (typeof toValuePtr !== 'object') {
        throw new Error('value parameter provided is not a pointer');
    }

    if (Buffer.isBuffer(from)) {
        decodeArg(dc, from, toValuePtr);
    } else if (from != null) {
        const pointer = toValuePtr as { value?: unknown };
        const isBox = Object.prototype.hasOwnProperty.call(pointer, 'value');
        const target = isBox ? pointer.value : toValuePtr;

        let assignable = target == null || typeof from === typeof target;

        if (assignable && Array.isArray(from) !== Array.isArray(target)) {
            assignable = false;
        }

        if (assignable && Buffer.isBuffer(from) !== Buffer.isBuffer(target)) {
            assignable = false;
        }

        const isPlainObject = (value: unknown): value is Record<string, unknown> =>
            value !== null &&
            typeof value === 'object' &&
            !Array.isArray(value) &&
            !Buffer.isBuffer(value) &&
            Object.getPrototypeOf(value) === Object.prototype;

        if (assignable && isPlainObject(from) && isPlainObject(target)) {
            const fromKeys = Object.keys(from).sort();
            const targetKeys = Object.keys(target).sort();
            assignable =
                fromKeys.length === targetKeys.length &&
                fromKeys.every((key, index) => key === targetKeys[index]);
        }

        if (!assignable) {
            const typeName = (value: unknown): string => {
                if (value == null) {
                    return '';
                }
                if (typeof value === 'object' || typeof value === 'function') {
                    return (value as { constructor?: { name?: string } }).constructor?.name ?? '';
                }
                return typeof value;
            };
            throw new Error(`${typeName(from)} is not assignable to  ${typeName(target)}`);
        }

        if (isBox) {
            pointer.value = from;
        } else {
            Object.assign(toValuePtr, from);
        }
    }
}

