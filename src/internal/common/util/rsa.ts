import { createPrivateKey, createPublicKey, KeyObject } from 'node:crypto';
import { goMarkLastParamByteSlice } from '../../runtime/reflect.js';

export enum KeyType {
  KeyTypePrivate = "private key",
  KeyTypePublic = "public key",
}

export function loadRSAKey(keyString: Buffer, keyType: KeyType): unknown {
  const pemString = keyString.toString();
  const header = pemString.match(/-----BEGIN ([^-]+)-----/m);

  if (header == null || header[1].toLowerCase() !== keyType.toLowerCase()) {
    throw new Error(`failed to parse PEM block containing the ${keyType}`);
  }

  switch (keyType) {
    case KeyType.KeyTypePrivate: {
      try {
        const key = createPrivateKey({ key: pemString, format: "pem" });
        return key;
      } catch (err) {
        throw new Error(
          `failed to parse DER encoded ${keyType}: ${err instanceof Error ? err.message : String(err)}`,
        );
      }
    }
    case KeyType.KeyTypePublic: {
      try {
        const key = createPublicKey({ key: pemString, format: "pem" });
        return key;
      } catch (err) {
        throw new Error(
          `failed to parse DER encoded ${keyType}: ${err instanceof Error ? err.message : String(err)}`,
        );
      }
    }
    default:
      throw new Error("invalid Key Type");
  }
}

export function LoadRSAPublicKey(key: Buffer): KeyObject {
  const rsaKey = loadRSAKey(key, KeyType.KeyTypePublic);
  return rsaKey as KeyObject;
}

export function LoadRSAPrivateKey(key: Buffer): KeyObject {
  const rsaKey = loadRSAKey(key, KeyType.KeyTypePrivate);
  return rsaKey as KeyObject;
}

